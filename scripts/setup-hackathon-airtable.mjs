#!/usr/bin/env node
// Creates the single AI Policy Competition table in the club's Airtable base. Nothing else in the base is touched.
// Safe to re-run: if the table exists, only missing fields are added.
//
// Usage (from the repository root):
//   node --env-file=.env.local scripts/setup-hackathon-airtable.mjs
//
// Needs HACKATHON_AIRTABLE_BASE_ID and a token (HACKATHON_AIRTABLE_TOKEN, or airtable_api) with the scopes
// data.records:read, data.records:write, schema.bases:read and schema.bases:write on that base.
// Field names must match lib/hackathon/airtable.ts.

const BASE_ID = process.env.HACKATHON_AIRTABLE_BASE_ID;
const TOKEN = (process.env.HACKATHON_AIRTABLE_TOKEN ?? process.env.airtable_api ?? "").trim().replace(/^Bearer\s+/i, "");
const TABLE = process.env.HACKATHON_AIRTABLE_TABLE ?? "AI Policy Competition 2026";

const ACADEMIC_STATUSES = [
  "First Year", "Second Year", "Third Year", "Fourth Year", "Law Student", "PhD",
  "Masters Student", "Post Doc", "Professional", "Faculty", "Other",
];

const dateTime = { type: "dateTime", options: { dateFormat: { name: "us" }, timeFormat: { name: "12hour" }, timeZone: "America/New_York" } };
const checkbox = { type: "checkbox", options: { icon: "check", color: "greenBright" } };
const score = { type: "number", options: { precision: 1 } };

// One row per participant, plus one row per brief upload. Group by Team Code to see each team.
const FIELDS = [
  { name: "Name", type: "singleLineText", description: "Participant's name, or “Brief: <team>” for a submission row." },
  { name: "Type", type: "singleSelect", options: { choices: [{ name: "Participant", color: "blueLight2" }, { name: "Submission", color: "orangeLight2" }] } },
  { name: "Team Name", type: "singleLineText" },
  { name: "Team Code", type: "singleLineText", description: "6-character code generated by the website. Group by this field to see each team." },
  { name: "Solo", ...checkbox },
  { name: "Email", type: "email" },
  { name: "Academic Status", type: "singleSelect", options: { choices: ACADEMIC_STATUSES.map((name) => ({ name })) } },
  { name: "School", type: "singleLineText" },
  { name: "Major/Minor", type: "singleLineText" },
  { name: "Timestamp", ...dateTime, description: "When the person registered, or when the brief was uploaded." },
  { name: "Brief PDF", type: "multipleAttachments", options: { isReversed: false } },
  { name: "Filename", type: "singleLineText" },
  { name: "Size (KB)", type: "number", options: { precision: 0 } },
  { name: "Technical Feasibility", ...score },
  { name: "Legal Feasibility", ...score },
  { name: "Addresses the Task", ...score },
  { name: "Top 6", ...checkbox },
  { name: "Judging Slot", ...dateTime },
  { name: "Notes", type: "multilineText" },
];

async function meta(path, init = {}) {
  const apiUrl = process.env.HACKATHON_AIRTABLE_API_URL ?? "https://api.airtable.com/v0";
  const response = await fetch(`${apiUrl}/meta/bases/${BASE_ID}/${path}`, {
    ...init,
    headers: { Authorization: `Bearer ${TOKEN}`, "Content-Type": "application/json" },
  });
  if (!response.ok) throw new Error(`Airtable ${init.method ?? "GET"} ${path} failed (${response.status}): ${await response.text()}`);
  return response.json();
}

async function main() {
  if (!BASE_ID || !TOKEN) {
    throw new Error("Set HACKATHON_AIRTABLE_BASE_ID and HACKATHON_AIRTABLE_TOKEN (or airtable_api) in .env.local first.");
  }

  const { tables } = await meta("tables");
  const current = tables.find((table) => table.name === TABLE);

  if (!current) {
    const created = await meta("tables", {
      method: "POST",
      body: JSON.stringify({
        name: TABLE,
        description: "AI Policy Competition registrations (Participant rows) and brief uploads (Submission rows), written by the website.",
        fields: FIELDS,
      }),
    });
    console.log(`Created table “${TABLE}” (${created.id}) with ${FIELDS.length} fields.`);
    return;
  }

  const have = new Set(current.fields.map((field) => field.name));
  const missing = FIELDS.filter((field) => !have.has(field.name));
  for (const field of missing) {
    await meta(`tables/${current.id}/fields`, { method: "POST", body: JSON.stringify(field) });
    console.log(`Added field ${field.name}`);
  }
  console.log(`Table “${TABLE}” is ready (${current.id})${missing.length ? "" : "; nothing to change"}.`);
}

main().catch((error) => {
  console.error(error.message);
  process.exit(1);
});
